// Play, pause or stop by what the next press of the key would do.
export function PlayWhat({ what = 'play', ...rest }) {
  return what === 'pause' ? <Pause {...rest} /> : what === 'stop' ? <Stop {...rest} /> : <Play {...rest} />
}
