// Severed's glyphs: bitmaps on a twelve-by-twelve grid (the display's clock on the
// twelve-by-ten of its lettering), as a terminal's
// character generator would hold them, drawn for this theme. Each is written
// out a row at a time ('#' lit, '.' dark) and turned into one path of whole
// cells, so it stays crisp at any whole multiple of twelve.

function pathOf(rows) {
  let d = ''
  rows.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      if (row[x] !== '#') { x += 1; continue }
      let end = x
      while (end < row.length && row[end] === '#') end += 1
      d += `M${x} ${y}h${end - x}v1h-${end - x}z`
      x = end
    }
  })
  return d
}

export const BITMAPS = {}
function glyph(name, rows) {
  BITMAPS[name] = rows
  const d = pathOf(rows)
  function Glyph({ size = 24, className = '', ...rest }) {
    return (
      <svg width={size} height={size} viewBox={`0 0 ${rows[0].length} ${rows.length}`} shapeRendering="crispEdges" fill="currentColor" aria-hidden="true" focusable="false"
           className={['sv-glyph', className].filter(Boolean).join(' ')} {...rest}>
        <path d={d} />
      </svg>
    )
  }
  Glyph.displayName = name
  return Glyph
}

